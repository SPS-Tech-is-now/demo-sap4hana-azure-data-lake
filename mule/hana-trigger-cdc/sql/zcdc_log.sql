-- hana-trigger-cdc — Tabla de log CDC y triggers LIGEROS (SAP HANA)
-- Requiere licencia HANA ENTERPRISE (Opción 1). Con licencia runtime NO aplica.
-- Esquema SAP de ejemplo: SAPABAP1. Ejecutar con usuario técnico con privilegios
-- CREATE ANY / TRIGGER sobre el esquema. Validar con Basis y SAP antes de producción
-- (SAP SLT usa el mismo principio de triggers de base de datos).
--
-- Diseño "trigger ligero": el trigger SOLO escribe la llave del registro cambiado.
-- Mule lee la imagen completa (after) en la misma transacción → impacto mínimo en SAP.
-- =====================================================================

CREATE COLUMN TABLE "SAPABAP1"."ZCDC_LOG" (
    "SEQ"        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "TABNAME"    NVARCHAR(30)  NOT NULL,
    "OP"         NVARCHAR(1)   NOT NULL,            -- I / U / D
    "KEY_JSON"   NVARCHAR(500) NOT NULL,            -- llave de negocio en JSON
    "CHANGE_TS"  TIMESTAMP     DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,
    "STATUS"     NVARCHAR(10)  DEFAULT 'NEW' NOT NULL,  -- NEW → PROCESSED (Mule)
    PRIMARY KEY ("SEQ")
);
CREATE INDEX "ZCDC_LOG_STATUS" ON "SAPABAP1"."ZCDC_LOG" ("STATUS", "SEQ");

-- ---------- VBAP (posiciones de pedido) ----------
CREATE TRIGGER "SAPABAP1"."ZCDC_VBAP_I" AFTER INSERT ON "SAPABAP1"."VBAP"
REFERENCING NEW ROW NR FOR EACH ROW
BEGIN
    INSERT INTO "SAPABAP1"."ZCDC_LOG" ("TABNAME", "OP", "KEY_JSON")
    VALUES ('VBAP', 'I', '{"MANDT":"' || :NR."MANDT" || '","VBELN":"' || :NR."VBELN" || '","POSNR":"' || :NR."POSNR" || '"}');
END;

CREATE TRIGGER "SAPABAP1"."ZCDC_VBAP_U" AFTER UPDATE ON "SAPABAP1"."VBAP"
REFERENCING NEW ROW NR FOR EACH ROW
BEGIN
    INSERT INTO "SAPABAP1"."ZCDC_LOG" ("TABNAME", "OP", "KEY_JSON")
    VALUES ('VBAP', 'U', '{"MANDT":"' || :NR."MANDT" || '","VBELN":"' || :NR."VBELN" || '","POSNR":"' || :NR."POSNR" || '"}');
END;

CREATE TRIGGER "SAPABAP1"."ZCDC_VBAP_D" AFTER DELETE ON "SAPABAP1"."VBAP"
REFERENCING OLD ROW OR_ FOR EACH ROW
BEGIN
    INSERT INTO "SAPABAP1"."ZCDC_LOG" ("TABNAME", "OP", "KEY_JSON")
    VALUES ('VBAP', 'D', '{"MANDT":"' || :OR_."MANDT" || '","VBELN":"' || :OR_."VBELN" || '","POSNR":"' || :OR_."POSNR" || '"}');
END;

-- ---------- BSID (partidas abiertas de clientes) ----------
-- Al COMPENSAR una partida, SAP la BORRA de BSID y la INSERTA en BSAD:
-- el trigger de DELETE es lo que permite reflejar la compensación en el lake.
CREATE TRIGGER "SAPABAP1"."ZCDC_BSID_I" AFTER INSERT ON "SAPABAP1"."BSID"
REFERENCING NEW ROW NR FOR EACH ROW
BEGIN
    INSERT INTO "SAPABAP1"."ZCDC_LOG" ("TABNAME", "OP", "KEY_JSON")
    VALUES ('BSID', 'I', '{"MANDT":"' || :NR."MANDT" || '","BUKRS":"' || :NR."BUKRS" || '","KUNNR":"' || :NR."KUNNR" || '","GJAHR":"' || :NR."GJAHR" || '","BELNR":"' || :NR."BELNR" || '","BUZEI":"' || :NR."BUZEI" || '"}');
END;

CREATE TRIGGER "SAPABAP1"."ZCDC_BSID_D" AFTER DELETE ON "SAPABAP1"."BSID"
REFERENCING OLD ROW OR_ FOR EACH ROW
BEGIN
    INSERT INTO "SAPABAP1"."ZCDC_LOG" ("TABNAME", "OP", "KEY_JSON")
    VALUES ('BSID', 'D', '{"MANDT":"' || :OR_."MANDT" || '","BUKRS":"' || :OR_."BUKRS" || '","KUNNR":"' || :OR_."KUNNR" || '","GJAHR":"' || :OR_."GJAHR" || '","BELNR":"' || :OR_."BELNR" || '","BUZEI":"' || :OR_."BUZEI" || '"}');
END;

